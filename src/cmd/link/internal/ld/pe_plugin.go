// PE output for the host<->plugin export boundary.
//
// Windows has no symbol interposition: a plugin DLL reaches the host only
// through an import table written at link time, and the host must carry an
// export table naming everything a plugin may bind to. The functions here
// build both sides of that boundary -- the .def files handed to an external
// linker, the well-known go:plugin.* exports the runtime reads at load, and
// the cgo runtime-init export a cgo plugin needs to complete its handshake.
//
// They live apart from pe.go, which is upstream's PE writer, so that upstream
// changes to it merge without touching fork-authored code. See
// trendvidia/go#140.

package ld

import (
	"bytes"
	"cmd/link/internal/loader"
	"cmd/link/internal/sym"
	"internal/pluginabi"
	"os"
	"path/filepath"
	"slices"
	"sort"
	"strings"
)

// peExportArgs appends a -def: file flag to st.argv that tells the
// linker how to populate the PE export table. Self-guards against the
// case where the user has already supplied -extldflags=...
// export-all-symbols (assumed manual control), so the call site can
// invoke unconditionally on Windows.
//
// MSVC lld-link uses -Wl,-def: with a different prefix from the
// MinGW form (which omits the prefix entirely and lets gcc supply it
// via /implib equivalence). The wlPrefix-driven branch in peArgs
// records which mode is in effect; here we only need to know the
// MSVC-vs-MinGW split via st.isMSVC.
func peExportArgs(ctxt *Link, st *hostlinkState) {
	if ctxt.BuildMode == BuildModePlugin {
		// Plugin DLLs export the symbols collected via
		// go:plugin.exports (each PluginExport gets CgoExportDynamic
		// in deadcode.go). Generate a .def file so mingw ld
		// exports them deterministically — relying on mingw's
		// --export-all-symbols auto-export skips BSS data
		// (`var X int`) in some cases, leaving the host's
		// plugin.Open(...).Lookup() unable to find them via
		// GetProcAddress.
		fileName := pePluginExportFile(ctxt)
		if fileName != "" {
			prefix := ""
			if st.isMSVC {
				prefix = "-Wl,-def:"
			}
			st.argv = append(st.argv, prefix+fileName)
		}
		return
	}
	if slices.Contains(flagExtldflags, st.wlPrefix+"export-all-symbols") {
		return
	}
	if ctxt.canUsePlugins {
		// Plugin host: export the symbols plugin DLLs link against.
		//
		// This cannot be --export-all-symbols. That flag publishes
		// every symbol in the image, and a PE image can only address
		// 65535 exports, so mingw ld rejects any host large enough to
		// exceed it outright ("export ordinal too large: N") — a real
		// application reaches that count just by being large. The .def
		// lists peHostExports' bounded set, the same set
		// peGenerateImportLibrary writes into host.exe.a. Exporting
		// more than that archive holds never helped: a plugin only
		// imports names it finds in the archive's symbol index.
		//
		// The host import library (.a) is generated by
		// peGenerateImportLibrary in the IMPORT_OBJECT format ld can
		// fully parse and pull stubs from. We do NOT pass
		// -Wl,--out-implib here because mingw ld writes the archive in
		// a compact (per-member) format ld can scan but not extract
		// from once references are open; that breaks the external-link
		// plugin path where peLoadImportLibrary converts runtime
		// functions to SHOSTOBJ and the plugin link needs ld to
		// actually pull the corresponding stubs from host.exe.a.
		fileName := peHostExportFile(ctxt)
		if fileName != "" {
			prefix := ""
			if st.isMSVC {
				prefix = "-Wl,-def:"
			}
			st.argv = append(st.argv, prefix+fileName)
		}
		return
	}
	fileName := peCreateExportFile(ctxt, filepath.Base(st.outopt))
	prefix := ""
	if st.isMSVC {
		prefix = "-Wl,-def:"
	}
	st.argv = append(st.argv, prefix+fileName)
}

// hasPluginPkg reports whether the plugin package is part of this link.
func hasPluginPkg(ctxt *Link) bool {
	if ctxt.LibraryByPkg["plugin"] != nil {
		return true
	}
	// Also check the library list directly in case the map key differs.
	for _, lib := range ctxt.Library {
		if lib.Pkg == "plugin" {
			return true
		}
	}
	return false
}

// peOutputDisplayName returns the user-visible name of the image being
// linked, for diagnostics. cmd/go links to objdir/a.out.exe (a.out.dll
// for plugins) and copies to the requested path afterwards, passing the
// real name via -pluginexename for every Windows link with -o, so the
// output-file base is not what the user asked to build. Naming the temp
// file in a diagnostic points the reader at a path that no longer exists
// by the time they read it.
//
// peGenerateImportLibrary picks the DLL name the same way; keep the two
// in step so a message and the import library agree on what to call the
// image.
func peOutputDisplayName() string {
	if *flagPluginExeName != "" {
		return *flagPluginExeName
	}
	return filepath.Base(*flagOutfile)
}

// pePluginExportFile creates a .def file listing every CgoExportDynamic
// symbol in the plugin DLL. Returns the file path, or "" if no symbols
// to export. The .def file's EXPORTS list overrides mingw ld's
// --export-all-symbols heuristics, which skip BSS data symbols whose
// only incoming reloc is from a RODATA carrier (see deadcode.go's
// go:plugin.exports handling).
func pePluginExportFile(ctxt *Link) string {
	ldr := ctxt.loader
	var names []string
	// ABI-mangle and de-duplicate as initdynexport (pe.go) and the
	// import-library walk (pe_implib.go) do. Three walks over the same
	// export set had drifted into three disciplines: this one took the
	// raw SymName and never de-duplicated. On the unmangled name a
	// function carrying both an ABI0 and an ABIInternal text symbol
	// yields the same string twice -- so the .def listed it twice and
	// named the ABI0 body not at all, though initdynexport's comment
	// explains why external-link plugins are the case that needs the
	// ABI0 export by name. No plugin export set observed at 60fd56dbc4
	// contains such a pair (measured: trendvidia/go#53), so this is
	// latent rather than a live defect -- which is exactly why it ships
	// with the pin in TestPluginExportFileABIPairs rather than waiting
	// for a plugin that trips it.
	//
	// The name basis stays SymName, and deliberately does not follow the
	// other two walks onto SymExtname. Those two write names the loader
	// reads (the PE export directory, the import library), where extname
	// is the intended public name and nothing has to resolve it. This
	// .def is an input to mingw ld/lld-link, whose EXPORTS lines must
	// name symbols defined in the object this link just emitted -- and
	// writeSymbols above names defined symbols by SymName, substituting
	// SymExtname only for SHOSTOBJ/SUNDEFEXT host imports. A two-argument
	// //go:cgo_export_dynamic Local Remote sets extname to Remote (see
	// go.go), so naming the .def by extname would ask ld to export a
	// symbol no object defines. Publishing such a symbol under its remote
	// name would need the "Remote = Local" .def form, which nothing needs
	// today; TestPluginExportFileABIPairs pins the SymName basis.
	seen := make(map[string]bool)
	for s := loader.Sym(1); s < loader.Sym(ldr.NSym()); s++ {
		if !ldr.AttrReachable(s) || !ldr.AttrCgoExportDynamic(s) {
			continue
		}
		name := mangleABIName(ctxt, ldr, s, ldr.SymName(s))
		if peSkipSymName(name) || seen[name] {
			continue
		}
		seen[name] = true
		names = append(names, name)
	}
	if len(names) == 0 {
		return ""
	}
	sort.Strings(names)
	// An early guard on the PINNED list only -- not the cap on the image.
	// Handing mingw ld an EXPORTS list does not switch its auto-export
	// off, so what this file names and what the image publishes are
	// different numbers (measured 6 vs 2195, trendvidia/go#59). The cap
	// that binds is peVerifyImageExportCount, which reads the finished
	// image after hostlink. This one only catches a pinned set so large
	// it cannot fit, and it is worth keeping because it fails before the
	// expensive link rather than after it.
	if len(names) > peExportLimit {
		Errorf("link: %s pins %d symbols in its export .def, more than the %d a PE image can address; reduce the exported surface",
			peOutputDisplayName(), len(names), peExportLimit)
		errorexit()
	}

	fname := filepath.Join(*flagTmpdir, "plugin_exports.def")
	var buf bytes.Buffer
	buf.WriteString("EXPORTS\n")
	for _, name := range names {
		buf.WriteString(name)
		buf.WriteByte('\n')
	}
	if err := os.WriteFile(fname, buf.Bytes(), 0666); err != nil {
		Errorf("WriteFile %s failed: %v", fname, err)
	}
	return fname
}

// peCgoExportNames returns the names of the functions this binary
// publishes via cgo's //export directive. peSkipSymName filters the
// underlying `_cgoexp_hashcode_symname` symbols out of the plugin-host
// export set, so callers building a host .def have to add these back
// explicitly or a host that both hosts plugins and exports to C would
// lose its C-visible entry points.
func peCgoExportNames(ctxt *Link) []string {
	ldr := ctxt.loader
	var exports []string
	for s := range ldr.ForAllCgoExportStatic() {
		extname := ldr.SymExtname(s)
		if !strings.HasPrefix(extname, "_cgoexp_") {
			continue
		}
		if ldr.IsFileLocal(s) {
			continue // Only export non-static symbols
		}
		// Retrieve the name of the initial symbol
		// exported by cgo.
		// The corresponding Go symbol is:
		// _cgoexp_hashcode_symname.
		name := strings.SplitN(extname, "_", 4)[3]
		exports = append(exports, name)
	}
	return exports
}

// peDefQuote renders name for a .def EXPORTS line, always double-quoted.
//
// Go symbol names are not .def identifiers. The grammar splits tokens on
// whitespace, starts a comment at `;`, and reads `=` as a rename, all of
// which occur in ordinary export names — generic instantiations carry
// spaces and semicolons inside the shape (`p.f[go.shape.struct { a int
// }]`), and gclocals names end in base64 `=` padding. Even a plain
// dotted name like `runtime.mheap_` is rejected bare by binutils' .def
// parser (verified against mingw-w64 binutils 2.45, ld 15.2.0).
//
// A quoted string is accepted wherever the grammar expects an
// identifier, and the quotes are stripped before the name reaches the
// export table, so quoting unconditionally is both correct and the only
// form that works across every name shape.
//
// There is no escape for a quote inside a quoted name, so a name holding
// one cannot be written at all. Only `go:string."..."` carriers have
// that shape and peSnapshotHostExports drops the whole `go:` class, so
// reaching the error means a new symbol class showed up and needs a
// decision — better than emitting a .def the external linker will
// misparse into an unrelated error.
func peDefQuote(name string) string {
	if strings.ContainsAny(name, "\"\r\n") {
		Errorf("cannot export %q: name is not representable in a .def EXPORTS entry", name)
		return ""
	}
	return `"` + name + `"`
}

// peHostExportFile creates the .def file bounding a plugin host's PE
// export table, and returns its path.
//
// The list is peHostExports' — identical to the symbol index of the
// host.exe.a that peGenerateImportLibrary wrote during asmb2, so a
// plugin cannot resolve an import the host failed to export — plus the
// binary's own cgo //export entry points, which are not part of the
// host<->plugin boundary but would otherwise disappear when the host
// stops using --export-all-symbols.
func peHostExportFile(ctxt *Link) string {
	symbols := peHostExports(ctxt.loader)
	if len(symbols) == 0 {
		Errorf("no host exports for %s; plugins would have nothing to bind to at load time", *flagOutfile)
		return ""
	}
	names := make([]string, 0, len(symbols))
	seen := make(map[string]bool, len(symbols))
	for _, s := range symbols {
		names = append(names, s.name)
		seen[s.name] = true
	}
	for _, name := range peCgoExportNames(ctxt) {
		if !seen[name] {
			seen[name] = true
			names = append(names, name)
		}
	}
	sort.Strings(names)

	fname := filepath.Join(*flagTmpdir, "host_exports.def")
	var buf bytes.Buffer
	buf.WriteString("EXPORTS\n")
	for _, name := range names {
		buf.WriteString(peDefQuote(name))
		buf.WriteByte('\n')
	}
	if err := os.WriteFile(fname, buf.Bytes(), 0666); err != nil {
		Errorf("WriteFile %s failed: %v", fname, err)
	}
	return fname
}

// addPluginPkghashesExport creates the go:plugin.pkghashes well-known
// export — a slice header (ptr, len, cap) referencing the eventual
// go:link.pkghashes carrier. Marked reachable + CgoExportDynamic so
// peExportAllSymbols / initdynexport / addexports route it into the
// plugin DLL's PE export directory. The carrier itself is populated by
// symtab.go's pkghashes block; the R_ADDR reloc here resolves at the
// final address-assignment phase.
func addPluginPkghashesExport(ctxt *Link) {
	ldr := ctxt.loader
	carrier := ldr.LookupOrCreateSym("go:link.pkghashes", 0)
	ldr.SetAttrReachable(carrier, true)

	export := ldr.CreateSymForUpdate("go:plugin.pkghashes", 0)
	export.SetType(sym.SRODATA)
	export.AddAddr(ctxt.Arch, carrier)
	export.AddUint(ctxt.Arch, uint64(len(ctxt.Library)))
	export.AddUint(ctxt.Arch, uint64(len(ctxt.Library)))
	ldr.SetAttrReachable(export.Sym(), true)
	ldr.SetAttrCgoExportDynamic(export.Sym(), true)
}

// addPluginAbiExport creates the go:plugin.abi well-known export — an
// 8-byte {pluginabi.Marker, pluginabi.Version} pair identifying the
// toolchain generation that built this DLL. package plugin on Windows
// reads it from the candidate FILE's export table before LoadLibrary
// and rejects binaries from an incompatible generation before their
// DllMain runs (trendvidia/go#24, part 2; the bump rules live in
// internal/pluginabi). Same routing as go:plugin.pkghashes: reachable
// + CgoExportDynamic so every export-table writer (internal linking
// here, .def for external) picks it up.
func addPluginAbiExport(ctxt *Link) {
	ldr := ctxt.loader
	export := ldr.CreateSymForUpdate("go:plugin.abi", 0)
	export.SetType(sym.SRODATA)
	export.AddUint32(ctxt.Arch, pluginabi.Marker)
	export.AddUint32(ctxt.Arch, pluginabi.Version)
	ldr.SetAttrReachable(export.Sym(), true)
	ldr.SetAttrCgoExportDynamic(export.Sym(), true)
}

// addCgoNotifyExport publishes x_cgo_notify_runtime_init_done from a
// plugin that contains runtime/cgo.
//
// Such a plugin carries its own libcgo, with its own runtime_init_done
// flag that starts out clear. Every C->Go entry point cgo generates
// opens with _cgo_wait_runtime_init_done (cmd/cgo/out.go), which blocks
// until that flag is set, and the only thing that sets it is
// x_cgo_notify_runtime_init_done — which plugin.Open calls by
// GetProcAddress once the image is loaded and its slots are
// canonicalised. If the name is not in the export table, Open cannot
// find it, and the plugin's first callback from C into Go never returns.
//
// Nothing put it there on purpose. On mingw it was present because ld
// auto-exports what it can, which is also why this went unnoticed:
// measured on windows_omen at 376044e969, a plugin whose .def named 6
// symbols published 2195, the notify among them. Narrow that — the .def
// becomes authoritative under -Wl,--exclude-all-symbols — and the export
// goes with it. The same plugin then published 6 names, loaded, ran a
// Go->C call fine (that direction carries no handshake) and hung forever
// on its first C->Go callback (trendvidia/go#62).
//
// Both link modes, deliberately. windows/arm64 links plugins internally
// (external linking of a cgo plugin there fails outright, #131) and
// published no notify at all: 25 exported names, none of them this. Its
// callbacks nonetheless ran, which they had no right to do — the flag
// they wait on had no writer — so that path was working by accident and
// is tracked as #130. Exporting here is half of closing it; the other
// half is package plugin calling the notify after lastmoduleinit rather
// than before, without which this export is not merely useless on the
// internal path but fatal, since the C code's Windows-API calls go
// through slots that are still empty that early.
//
// peSkipSymName drops names beginning with '_', which is why the symbol
// is reachable at all under its own 'x' name.
func addCgoNotifyExport(ctxt *Link) {
	if !iscgo {
		return
	}
	ldr := ctxt.loader
	s := ldr.Lookup("x_cgo_notify_runtime_init_done", 0)
	if s == 0 {
		return
	}
	if ctxt.LinkMode == LinkExternal {
		// The .def is a request to mingw ld, which resolves the name
		// out of libcgo itself; this linker never sees a definition and
		// never lays one out (measured: SHOSTOBJ, value 0, not
		// reachable, for every external-link plugin). Marking it
		// reachable is only how it reaches pePluginExportFile's walk.
		ldr.SetAttrReachable(s, true)
	} else if !ldr.AttrReachable(s) {
		// Internal linking, and this image does not contain libcgo's C
		// half: `import "C"` alone puts runtime/cgo in the link (so
		// iscgo is set) without pulling in anything that references the
		// notify, and deadcode drops it. There is then nothing to
		// notify -- no _cgo_wait_runtime_init_done in the image either,
		// so nothing can block -- and nothing to publish.
		//
		// Publishing it anyway is not harmless, which is how this arm
		// was found: this linker writes the export table itself on the
		// internal path, and an unreachable symbol has no address yet,
		// so the export got the placeholder. Measured on windows/arm64,
		// a plugin whose only cgo is `import "C"` published the notify
		// at RVA 0xc00003e8; GetProcAddress handed plugin.Open
		// base+0x3e8, inside the PE headers, and the call died on an
		// execute violation (0xc0000005 info 0x8) taking six tests with
		// it.
		return
	}
	ldr.SetAttrCgoExportDynamic(s, true)
}
